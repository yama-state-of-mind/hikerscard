-- ---------- 山マスタ（349座） ----------
create table public.mountains (
  id          smallint generated by default as identity primary key,
  name        text not null unique,
  kana        text not null,
  elevation   smallint,
  area        text,
  difficulty  smallint check (difficulty between 1 and 5),
  meizan_rank smallint check (meizan_rank in (100, 200, 300)),  -- null = その他
  region      text check (region in (
                'north', 'kita_alps', 'minami_alps', 'koshin',
                'kanto', 'tokai', 'west')),
  is_popular  boolean not null default false,
  prefs       text[] not null default '{}',   -- 都道府県（県境の山は複数）
  pref        text                             -- 旧列。コードからは未使用
);
create index mountains_kana_idx    on public.mountains (kana);
create index mountains_rank_idx    on public.mountains (meizan_rank);
create index mountains_region_idx  on public.mountains (region);
create index mountains_popular_idx on public.mountains (is_popular) where is_popular;

-- ---------- プロフィール（カードの中身） ----------
create table public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  public_id     text not null unique,
  card_no       integer generated by default as identity not null,
  display_name  text not null default '' check (char_length(display_name) <= 20),
  comment       text check (char_length(comment) <= 120),
  type_code     text check (type_code ~ '^[A-Z]{4}$'),
  axis_pe       smallint check (axis_pe between 0 and 100),
  axis_sg       smallint check (axis_sg between 0 and 100),
  axis_lf       smallint check (axis_lf between 0 and 100),
  axis_ca       smallint check (axis_ca between 0 and 100),
  card_bg       text not null default 'contour'
                  check (card_bg in ('contour', 'ridge', 'mist', 'forest', 'night')),
  sns_yamap     text check (char_length(sns_yamap)     <= 60),
  sns_yamareco  text check (char_length(sns_yamareco)  <= 60),
  sns_instagram text check (char_length(sns_instagram) <= 60),
  sns_x         text check (char_length(sns_x)         <= 60),
  vis_rank_100  boolean not null default true,
  vis_rank_200  boolean not null default true,
  vis_rank_300  boolean not null default true,
  vis_rank_other boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create unique index profiles_card_no_idx on public.profiles (card_no);

-- ---------- 登った山（is_favorite = 行ってよかった山） ----------
create table public.climbed_mountains (
  user_id     uuid not null references public.profiles(id) on delete cascade,
  mountain_id smallint not null references public.mountains(id),
  is_favorite boolean not null default false,
  favorite_rank smallint check (favorite_rank between 1 and 5),   -- よかった山の順位
  created_at  timestamptz not null default now(),
  primary key (user_id, mountain_id)
);
create index climbed_favorite_idx on public.climbed_mountains (user_id) where is_favorite;
create unique index climbed_favorite_rank_uniq
  on public.climbed_mountains (user_id, favorite_rank) where favorite_rank is not null;

-- ---------- 登りたい山 ----------
create table public.wishlist_mountains (
  user_id     uuid not null references public.profiles(id) on delete cascade,
  mountain_id smallint not null references public.mountains(id),
  created_at  timestamptz not null default now(),
  primary key (user_id, mountain_id)
);

-- ---------- 交換トークン（10分有効のQR） ----------
create table public.exchange_tokens (
  token      text primary key,
  owner_id   uuid not null references public.profiles(id) on delete cascade,
  expires_at timestamptz not null,
  revoked    boolean not null default false,
  use_count  integer not null default 0,
  created_at timestamptz not null default now()
);
create index exchange_tokens_owner_idx on public.exchange_tokens (owner_id);

-- ---------- 交換の記録（1組1行、user_a < user_b） ----------
create table public.exchanges (
  id                uuid primary key default gen_random_uuid(),
  user_a            uuid not null references public.profiles(id) on delete cascade,
  user_b            uuid not null references public.profiles(id) on delete cascade,
  first_met_at      timestamptz not null default now(),
  last_exchanged_at timestamptz not null default now(),
  check (user_a < user_b),
  unique (user_a, user_b)
);

-- ---------- ブロック ----------
create table public.blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

-- ---------- 通報 ----------
create table public.reports (
  id          uuid primary key default gen_random_uuid(),
  reporter_id uuid references public.profiles(id) on delete set null,
  reported_id uuid not null references public.profiles(id) on delete cascade,
  reason      text not null,
  detail      text check (char_length(detail) <= 1000),
  status      text not null default 'open' check (status in ('open', 'resolved')),
  created_at  timestamptz not null default now()
);


