-- ---------- ランダム文字列 ----------

-- 公開ID用（紛らわしい文字 l/1/o/0 を除いた31文字）
create or replace function public.random_public_id(len integer default 6)
returns text language sql as $$
  select string_agg(
    substr('abcdefghjkmnpqrstuvwxyz23456789',
           (floor(random() * 31) + 1)::int, 1), '')
  from generate_series(1, len);
$$;

-- 交換トークン用（英数字62文字）
create or replace function public.random_token(len integer default 16)
returns text language sql as $$
  select string_agg(
    substr('abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789',
           (floor(random() * 62) + 1)::int, 1), '')
  from generate_series(1, len);
$$;


