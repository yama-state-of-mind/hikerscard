-- アカウント作成時に profiles 行を自動作成
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare new_id text;
begin
  loop
    new_id := public.random_public_id(6);
    exit when not exists (select 1 from public.profiles where public_id = new_id);
  end loop;
  insert into public.profiles (id, public_id) values (new.id, new_id);
  return new;
end;
$$;

-- ※ auth スキーマ側のトリガーなので、今回の書き出しには出ていない。
--    設計書 v1 の定義どおり存在する前提。
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 変更不可列の保護 ＋ updated_at 自動更新 ＋ 条件がそろったらカード番号を発行（Step 20）
create or replace function public.protect_profile_fields()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  need int;
begin
  new.updated_at := now();
  new.public_id  := old.public_id;   -- URLは変更不可
  new.card_no    := old.card_no;     -- カード番号も変更不可
  new.created_at := old.created_at;

  -- 完成の日時は、complete_onboarding が許可の印を立てたときだけ変えられる
  if coalesce(current_setting('hc.onboarding', true), '') <> '1' then
    new.onboarded_at := old.onboarded_at;
  end if;

  -- テスト用の印は、管理人（admin_set_tester）が許可の印を立てたときだけ変えられる
  if coalesce(current_setting('hc.tester', true), '') <> '1' then
    new.is_tester := old.is_tester;
  end if;

  -- カードの背景の鍵：交換した枚数が足りない背景には変えられない
  --   山なみ 1枚 ／ 朝焼け・雲海 3枚 ／ 地形図・夜空 5枚（card.js の THEMES と同じ表）
  --   いま使っている背景のまま（変えない）なら、枚数が足りなくてもそのまま使える
  if new.card_bg is distinct from old.card_bg then
    need := case new.card_bg
              when 'ridge'  then 1
              when 'morgen' then 3
              when 'unkai'  then 3
              when 'topo'   then 5
              when 'night'  then 5
              else 0 end;
    if need > 0 and (select count(*) from public.exchanges e
                      where new.id in (e.user_a, e.user_b)) < need then
      raise exception 'bg_locked';
    end if;
  end if;

  -- 完成したら、まだ番号の無い人に次の番号を振る
  if new.card_no is null and new.onboarded_at is not null then
    new.card_no := nextval('public.profiles_card_no_seq');
  end if;

  return new;
end;
$$;

create trigger on_profile_update
  before update on public.profiles
  for each row execute function public.protect_profile_fields();

-- 行ってよかった山は5座まで
create or replace function public.limit_favorites()
returns trigger language plpgsql as $$
begin
  if new.is_favorite and (
    select count(*) from public.climbed_mountains
     where user_id = new.user_id and is_favorite
       and mountain_id <> new.mountain_id
  ) >= 5 then
    raise exception 'favorite_limit';
  end if;
  return new;
end;
$$;

create trigger check_favorite_limit
  before insert or update on public.climbed_mountains
  for each row execute function public.limit_favorites();

-- 登りたい山は5座まで
create or replace function public.limit_wishlist()
returns trigger language plpgsql as $$
begin
  if (select count(*) from public.wishlist_mountains
       where user_id = new.user_id) >= 5 then
    raise exception 'wishlist_limit';
  end if;
  return new;
end;
$$;

create trigger check_wishlist_limit
  before insert on public.wishlist_mountains
  for each row execute function public.limit_wishlist();

-- ブロックしたら交換記録を削除
create or replace function public.on_block_created()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from public.exchanges
   where (user_a = least(new.blocker_id, new.blocked_id)
      and user_b = greatest(new.blocker_id, new.blocked_id));
  return new;
end;
$$;

create trigger after_block_insert
  after insert on public.blocks
  for each row execute function public.on_block_created();


