          ('100',   case when p.vis_rank_100   then public.meizan_counts(p.id)->'100'   end),
          ('200',   case when p.vis_rank_200   then public.meizan_counts(p.id)->'200'   end),
          ('300',   case when p.vis_rank_300   then public.meizan_counts(p.id)->'300'   end),
          ('other', case when p.vis_rank_other then public.meizan_counts(p.id)->'other' end)
        ) as t(k, v)
        where v is not null),
      'climbed',
        coalesce((select jsonb_agg(jsonb_build_object(
            'name', m.name, 'rank', m.meizan_rank)
            order by m.elevation desc nulls last)
          from public.climbed_mountains c
          join public.mountains m on m.id = c.mountain_id
         where c.user_id = p.id), '[]'::jsonb),
      'favorites',
        coalesce((select jsonb_agg(jsonb_build_object(
            'name', m.name, 'rank', m.meizan_rank, 'pos', c.favorite_rank)
            order by c.favorite_rank nulls last, m.elevation desc nulls last)
          from public.climbed_mountains c
          join public.mountains m on m.id = c.mountain_id
         where c.user_id = p.id and c.is_favorite), '[]'::jsonb),
      'wishlist',
        coalesce((select jsonb_agg(jsonb_build_object(
            'name', m.name, 'rank', m.meizan_rank)
            order by m.elevation desc nulls last)
          from public.wishlist_mountains w
          join public.mountains m on m.id = w.mountain_id
         where w.user_id = p.id), '[]'::jsonb),
      'first_met_at', e.first_met_at
    ) order by e.first_met_at desc)
    from public.exchanges e
    join public.profiles p
      on p.id = case when e.user_a = me then e.user_b else e.user_a end
   where me in (e.user_a, e.user_b)
  ), '[]'::jsonb);
end;
$$;

-- ---------- 山の登録をまとめて保存（Step 17） ----------
-- p_favorites は配列の順番がそのまま1位〜5位
create or replace function public.save_my_mountains(
  p_climbed   smallint[],
  p_favorites smallint[],
  p_wishlist  smallint[])
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me   uuid := auth.uid();
  clim smallint[];
  fav  smallint[];
  wish smallint[];
begin
  if me is null then raise exception 'not authenticated'; end if;

  -- 重複を除く（よかった山は順番を保つ）
  select coalesce(array_agg(distinct x), '{}') into clim
    from unnest(coalesce(p_climbed, '{}')) as x;

  select coalesce(array_agg(x order by first_pos), '{}') into fav
    from (select x, min(ord) as first_pos
            from unnest(coalesce(p_favorites, '{}')) with ordinality as t(x, ord)
           group by x) s;

  select coalesce(array_agg(distinct x), '{}') into wish
    from unnest(coalesce(p_wishlist, '{}')) as x;

  -- 検証
  if cardinality(fav) > 5 then raise exception 'favorite_limit'; end if;
  if cardinality(wish) > 5 then raise exception 'wishlist_limit'; end if;
  if not (fav <@ clim) then raise exception 'favorite_not_climbed'; end if;

  -- 登りたい山のうち、登った山に入っているものは外す
  select coalesce(array_agg(x), '{}') into wish
    from unnest(wish) as x where x <> all(clim);

  -- 登った山：外したものを消し、足したものを入れる
  delete from public.climbed_mountains
   where user_id = me and mountain_id <> all(clim);

  insert into public.climbed_mountains (user_id, mountain_id)
  select me, x from unnest(clim) as x
  on conflict (user_id, mountain_id) do nothing;

  -- よかった山：いったん全部外してから、順位を付け直す
  update public.climbed_mountains
     set is_favorite = false, favorite_rank = null
   where user_id = me and (is_favorite or favorite_rank is not null);

  update public.climbed_mountains c
     set is_favorite = true, favorite_rank = f.ord
    from unnest(fav) with ordinality as f(id, ord)
   where c.user_id = me and c.mountain_id = f.id;

  -- 登りたい山：入れ直す
  delete from public.wishlist_mountains where user_id = me;

  insert into public.wishlist_mountains (user_id, mountain_id)
  select me, x from unnest(wish) as x;

  return jsonb_build_object(
    'ok', true,
    'climbed', cardinality(clim),
    'favorites', cardinality(fav),
    'wishlist', cardinality(wish));
end;
$$;

-- ---------- 交換トークンの発行 ----------
create or replace function public.issue_exchange_token()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me uuid := auth.uid();
  t text;
  exp timestamptz := now() + interval '10 minutes';
begin
  if me is null then raise exception 'not authenticated'; end if;

  -- 表示名が未設定のうちは交換できない
  if (select onboarded_at from public.profiles where id = me) is null then   -- カードが完成していなければ交換できない
    raise exception 'profile not ready';
  end if;

  -- 既存の有効なトークンを無効化（同時に複数出さない）
  update public.exchange_tokens
     set revoked = true
   where owner_id = me and revoked = false and expires_at > now();

  loop
    t := public.random_token(16);
    exit when not exists (select 1 from public.exchange_tokens where token = t);
  end loop;

  insert into public.exchange_tokens (token, owner_id, expires_at)
  values (t, me, exp);

  return jsonb_build_object('token', t, 'expires_at', exp);
end;
$$;

-- ---------- 交換トークンの使用 ----------
create or replace function public.redeem_exchange_token(p_token text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me uuid := auth.uid();
  tok public.exchange_tokens%rowtype;
  a uuid; b uuid;
  is_new boolean;
begin
  if me is null then raise exception 'not authenticated'; end if;

  select * into tok from public.exchange_tokens where token = p_token;
  if not found then return jsonb_build_object('ok', false, 'reason', 'not_found'); end if;
  if tok.revoked then return jsonb_build_object('ok', false, 'reason', 'revoked'); end if;
  if tok.expires_at <= now() then return jsonb_build_object('ok', false, 'reason', 'expired'); end if;
  if tok.owner_id = me then return jsonb_build_object('ok', false, 'reason', 'self'); end if;

  -- どちらかがブロックしていたら交換できない
  if exists (
    select 1 from public.blocks
    where (blocker_id = tok.owner_id and blocked_id = me)
       or (blocker_id = me and blocked_id = tok.owner_id)
  ) then
    return jsonb_build_object('ok', false, 'reason', 'blocked');
  end if;

  -- 表示名が未設定なら交換できない
  if (select onboarded_at from public.profiles where id = me) is null then   -- カードが完成していなければ交換できない
    return jsonb_build_object('ok', false, 'reason', 'profile_not_ready');
  end if;

  a := least(me, tok.owner_id);
  b := greatest(me, tok.owner_id);

  insert into public.exchanges (user_a, user_b)
  values (a, b)
  on conflict (user_a, user_b)
    do update set last_exchanged_at = now()   -- first_met_at は上書きしない
  returning (xmax = 0) into is_new;

  update public.exchange_tokens
     set use_count = use_count + 1
   where token = p_token;

  -- 新しく交換できたら、QRを見せていた側に「交換しました」のお知らせを残す
  -- （読み取った側は、その場でお祝いの画面を見るので不要）
  if is_new then
    insert into public.notices (user_id, kind, partner_id)
    values (tok.owner_id, 'exchanged', me);
  end if;

  return jsonb_build_object(
    'ok', true,
    'is_new', is_new,
    'partner', (select public_id from public.profiles where id = tok.owner_id));
end;
$$;

-- ---------- 通報（あわせてブロックも可） ----------
create or replace function public.submit_report(
  p_public_id text, p_reason text,
  p_detail text default null, p_block boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me     uuid := auth.uid();
  target uuid;
begin
  select id into target from public.profiles where public_id = p_public_id;
  if target is null then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;

  if me is not null and me = target then
    return jsonb_build_object('ok', false, 'reason', 'self');
  end if;

  if p_reason is null or btrim(p_reason) = '' then
    return jsonb_build_object('ok', false, 'reason', 'no_reason');
  end if;

  insert into public.reports (reporter_id, reported_id, reason, detail)
  values (me, target, p_reason, nullif(btrim(coalesce(p_detail, '')), ''));

  -- あわせてブロックする場合（ログインしているときだけ）
  if p_block and me is not null then
    insert into public.blocks (blocker_id, blocked_id)
    values (me, target)
    on conflict do nothing;
  end if;

  return jsonb_build_object('ok', true);
end;
$$;

